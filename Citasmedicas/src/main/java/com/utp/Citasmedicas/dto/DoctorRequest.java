package com.utp.Citasmedicas.dto;

import jakarta.validation.constraints.*;

// Datos que manda el ADMIN para crear un doctor + su cuenta MEDICO
public class DoctorRequest {

    @NotBlank(message = "La colegiatura es obligatoria")
    @Pattern(regexp = "\\d{4,6}", message = "La colegiatura debe tener de 4 a 6 numeros")
    private String colegiatura;

    @NotBlank(message = "Los nombres son obligatorios")
    private String nombres;

    @NotBlank(message = "Los apellidos son obligatorios")
    private String apellidos;

    @NotNull(message = "La especialidad es obligatoria")
    private Long idEspecialidad;

    @Pattern(regexp = "\\d{9}", message = "El telefono debe tener 9 numeros")
    private String telefono;

    // Datos de su cuenta para iniciar sesion
    @NotBlank(message = "El correo es obligatorio")
    @Email(message = "El correo no es valido")
    private String correo;

    @NotBlank(message = "La contraseña es obligatoria")
    @Size(min = 6, message = "La contraseña debe tener al menos 6 caracteres")
    private String password;

    public DoctorRequest() {
    }

    public String getColegiatura() {
        return colegiatura;
    }

    public void setColegiatura(String colegiatura) {
        this.colegiatura = colegiatura;
    }

    public String getNombres() {
        return nombres;
    }

    public void setNombres(String nombres) {
        this.nombres = nombres;
    }

    public String getApellidos() {
        return apellidos;
    }

    public void setApellidos(String apellidos) {
        this.apellidos = apellidos;
    }

    public Long getIdEspecialidad() {
        return idEspecialidad;
    }

    public void setIdEspecialidad(Long idEspecialidad) {
        this.idEspecialidad = idEspecialidad;
    }

    public String getTelefono() {
        return telefono;
    }

    public void setTelefono(String telefono) {
        this.telefono = telefono;
    }

    public String getCorreo() {
        return correo;
    }

    public void setCorreo(String correo) {
        this.correo = correo;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }
}
