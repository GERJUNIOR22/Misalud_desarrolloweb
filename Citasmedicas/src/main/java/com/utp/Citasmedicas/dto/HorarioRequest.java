package com.utp.Citasmedicas.dto;

import com.utp.Citasmedicas.entity.DiaSemana;
import jakarta.validation.constraints.NotNull;

import java.time.LocalTime;

public class HorarioRequest {

    // Solo lo usa el ADMIN (el medico no la manda: sale de su token)
    private String colegiatura;

    @NotNull(message = "El dia es obligatorio (LUNES, MARTES...)")
    private DiaSemana diaSemana;

    @NotNull(message = "La hora de inicio es obligatoria")
    private LocalTime horaInicio;

    @NotNull(message = "La hora de fin es obligatoria")
    private LocalTime horaFin;

    public HorarioRequest() {
    }

    public String getColegiatura() {
        return colegiatura;
    }

    public void setColegiatura(String colegiatura) {
        this.colegiatura = colegiatura;
    }

    public DiaSemana getDiaSemana() {
        return diaSemana;
    }

    public void setDiaSemana(DiaSemana diaSemana) {
        this.diaSemana = diaSemana;
    }

    public LocalTime getHoraInicio() {
        return horaInicio;
    }

    public void setHoraInicio(LocalTime horaInicio) {
        this.horaInicio = horaInicio;
    }

    public LocalTime getHoraFin() {
        return horaFin;
    }

    public void setHoraFin(LocalTime horaFin) {
        this.horaFin = horaFin;
    }
}
